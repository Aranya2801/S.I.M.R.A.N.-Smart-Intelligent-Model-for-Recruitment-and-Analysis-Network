"""Writes web/js/model-data.js from simran/data/skills.json + models/simran_v3_core.json.

The browser can't fetch() local json when index.html is opened from disk, so
the data is inlined as a plain JS global instead.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from simran.taxonomy import load_taxonomy  # noqa: E402

tax = load_taxonomy()
model = json.loads((ROOT / "models" / "simran_v3_core.json").read_text())
data = {
    # already sorted longest-alias-first, same order python uses
    "patterns": [[a, c] for a, c, _ in tax._patterns],
    "categories": {k: v["category"] for k, v in tax.skills.items()},
    "related": {k: sorted(v) for k, v in tax.related.items()},
    "ambiguous": sorted(tax.ambiguous),
    "model": model,
}
out = ROOT / "web" / "js" / "model-data.js"
out.write_text("// generated by scripts/export_web_assets.py -- don't edit by hand\n"
               "const SIMRAN_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")
